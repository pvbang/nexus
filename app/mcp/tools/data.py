def _resolve_workspace_file(rel_path: str) -> Path | None:
    """Resolve a spreadsheet path within the task workspace (read side).

    Reuses filesystem's smart resolver so agents can pass the same path shapes
    they use elsewhere. Returns None if it escapes the workspace.
    """
    from app.mcp.tools.filesystem import (
        WORKSPACE_DIR as FS_WORKSPACE_DIR,
        _smart_resolve_path,
        get_task_workspace,
    )

    ws = get_task_workspace()
    path = _smart_resolve_path(rel_path, ws, FS_WORKSPACE_DIR)
    try:
        if not str(path.resolve()).startswith(str(FS_WORKSPACE_DIR.resolve())):
            return None
    except OSError:
        return None
    # Fallback to global workspace if not found in task workspace.
    if not path.exists() and ws != FS_WORKSPACE_DIR:
        alt = FS_WORKSPACE_DIR / rel_path
        if alt.exists():
            return alt
    return path


async def handle_read_spreadsheet(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Read an existing .xlsx/.xlsm spreadsheet into structured rows."""
    rel_path = params.get("path", "")
    sheet_name = params.get("sheet")
    max_rows = params.get("max_rows", 200)
    if not isinstance(max_rows, int) or max_rows < 1:
        max_rows = 200

    if not rel_path:
        return {"success": False, "output": "⚠️ 'path' is required.", "data": None, "artifacts": []}

    try:
        from openpyxl import load_workbook
    except ImportError:
        return {"success": False, "output": "openpyxl not installed. Run: pip install openpyxl", "data": None, "artifacts": []}

    path = _resolve_workspace_file(rel_path)
    if path is None:
        return {"success": False, "output": "Access denied: path resolves outside workspace.", "data": None, "artifacts": []}
    if not path.exists():
        return {"success": False, "output": f"File not found: {rel_path}", "data": None, "artifacts": []}

    try:
        wb = load_workbook(str(path), read_only=True, data_only=True)
    except Exception as e:  # noqa: BLE001
        return {"success": False, "output": f"Cannot open spreadsheet: {e}", "data": None, "artifacts": []}

    try:
        all_sheets = wb.sheetnames
        target = sheet_name or wb.active.title
        if target not in all_sheets:
            return {
                "success": False,
                "output": f"Sheet '{target}' not found. Available: {', '.join(all_sheets)}",
                "data": {"sheets": all_sheets},
                "artifacts": [],
            }
        ws = wb[target]

        rows: list[list[Any]] = []
        truncated = False
        for i, row in enumerate(ws.iter_rows(values_only=True)):
            if i >= max_rows:
                truncated = True
                break
            rows.append(["" if c is None else c for c in row])

        total_rows = ws.max_row
        total_cols = ws.max_column
    finally:
        wb.close()

    # Build a compact textual preview.
    preview_lines = [
        f"📗 {rel_path} | sheet '{target}' ({len(all_sheets)} sheet(s): {', '.join(all_sheets)})",
        f"   {total_rows} row(s) × {total_cols} col(s); showing {len(rows)}"
        + (" (truncated)" if truncated else ""),
        "",
    ]
    for idx, r in enumerate(rows, 1):
        cells = " | ".join(str(c)[:30] for c in r)
        preview_lines.append(f"   {idx}: {cells}")

    return {
        "success": True,
        "output": "\n".join(preview_lines),
        "data": {
            "path": rel_path,
            "sheet": target,
            "sheets": all_sheets,
            "rows": rows,
            "total_rows": total_rows,
            "total_cols": total_cols,
            "truncated": truncated,
        },
        "artifacts": [],
    }


async def handle_edit_spreadsheet(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Edit cells in an existing .xlsx in place, preserving other content/format.

    Provide `edits`: a list of {cell, value} (e.g. {"cell": "B2", "value": 42})
    OR {row, col, value} (1-based). Only the targeted cells change; everything
    else in the workbook is preserved. Writes atomically (temp file + replace).
    """
    rel_path = params.get("path", "")
    sheet_name = params.get("sheet")
    edits = params.get("edits")

    if not rel_path:
        return {"success": False, "output": "⚠️ 'path' is required.", "data": None, "artifacts": []}
    if not isinstance(edits, list) or not edits:
        return {
            "success": False,
            "output": "⚠️ 'edits' must be a non-empty array of {cell|row+col, value}.",
            "data": None,
            "artifacts": [],
        }

    try:
        from openpyxl import load_workbook
    except ImportError:
        return {"success": False, "output": "openpyxl not installed. Run: pip install openpyxl", "data": None, "artifacts": []}

    path = _resolve_workspace_file(rel_path)
    if path is None:
        return {"success": False, "output": "Access denied: path resolves outside workspace.", "data": None, "artifacts": []}
    if not path.exists():
        return {"success": False, "output": f"File not found: {rel_path}. Use generate_excel to create it.", "data": None, "artifacts": []}

    try:
        wb = load_workbook(str(path))  # full mode — preserves formatting on save
    except Exception as e:  # noqa: BLE001
        return {"success": False, "output": f"Cannot open spreadsheet: {e}", "data": None, "artifacts": []}

    applied: list[str] = []
    try:
        target = sheet_name or wb.active.title
        if target not in wb.sheetnames:
            wb.close()
            return {
                "success": False,
                "output": f"Sheet '{target}' not found. Available: {', '.join(wb.sheetnames)}",
                "data": None,
                "artifacts": [],
            }
        ws = wb[target]

        for idx, edit in enumerate(edits):
            if not isinstance(edit, dict) or "value" not in edit:
                wb.close()
                return {
                    "success": False,
                    "output": f"Edit #{idx + 1} must be an object with a 'value' (and 'cell' or 'row'+'col').",
                    "data": None,
                    "artifacts": [],
                }
            value = edit["value"]
            if "cell" in edit:
                coord = str(edit["cell"]).upper()
                try:
                    ws[coord] = value
                except (ValueError, KeyError) as e:
                    wb.close()
                    return {"success": False, "output": f"Edit #{idx + 1}: invalid cell '{coord}' ({e})", "data": None, "artifacts": []}
                applied.append(f"{coord}={value!r}")
            elif "row" in edit and "col" in edit:
                try:
                    ws.cell(row=int(edit["row"]), column=int(edit["col"]), value=value)
                except (ValueError, TypeError) as e:
                    wb.close()
                    return {"success": False, "output": f"Edit #{idx + 1}: invalid row/col ({e})", "data": None, "artifacts": []}
                applied.append(f"R{edit['row']}C{edit['col']}={value!r}")
            else:
                wb.close()
                return {"success": False, "output": f"Edit #{idx + 1}: provide 'cell' or both 'row' and 'col'.", "data": None, "artifacts": []}

        # Atomic save: write to temp then replace.
        import tempfile
        fd, tmp = tempfile.mkstemp(suffix=".xlsx", dir=str(path.parent))
        os.close(fd)
        try:
            wb.save(tmp)
            os.replace(tmp, str(path))
        except BaseException:
            try:
                os.unlink(tmp)
            except OSError:
                pass
            raise
    finally:
        wb.close()

    return {
        "success": True,
        "output": f"✏️ Edited {rel_path} (sheet '{target}'): {len(applied)} cell(s) — {', '.join(applied[:10])}",
        "data": {"path": rel_path, "sheet": target, "edits_applied": len(applied)},
        "artifacts": [{"type": "file", "path": rel_path}],
    }


