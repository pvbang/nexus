async def handle_parse_json(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Parse và format JSON data."""
    data = params.get("data", "")
    try:
        if isinstance(data, str):
            parsed = json.loads(data)
        else:
            parsed = data
        formatted = json.dumps(parsed, indent=2, ensure_ascii=False)
        return {"success": True, "output": formatted, "data": parsed, "artifacts": []}
    except Exception as e:
        return {"success": False, "output": f"Parse error: {e}", "data": None, "artifacts": []}


async def handle_generate_report(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Tạo report file (markdown)."""
    title = params.get("title", "Report")
    content = params.get("content", "")
    filename = params.get("filename", f"report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md")

    report = f"# {title}\n\n*Generated by Nexus at {datetime.now().isoformat()}*\n\n{content}"
    path = _get_output_dir() / filename
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report, encoding="utf-8")

    return {
        "success": True,
        "output": f"Report generated: {filename}",
        "data": {"path": filename, "size": len(report)},
        "artifacts": [{"type": "report", "path": filename, "format": "markdown"}],
    }


async def handle_generate_word_document(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """
    Tạo Word document (DOCX) từ markdown content.

    Enhanced features:
    - Markdown table → Word table conversion
    - Bold/italic/code inline formatting
    - Headings (H1-H4)
    - Bullet/numbered lists
    - Blockquotes
    - Horizontal rules
    - Robust error handling (KHÔNG fallback im lặng)
    """
    title = params.get("title", "Document")
    content = params.get("content", "")
    filename = params.get("filename", f"document_{datetime.now().strftime('%Y%m%d_%H%M%S')}.docx")

    try:
        from app.documents.docx import render_docx, docx_available
        if not docx_available():
            return {
                "success": False,
                "output": "❌ pandoc chưa được cài (cần để sinh .docx chuyên nghiệp). Cài: apt-get install pandoc",
                "data": {"error": "pandoc not installed"},
                "artifacts": [],
            }
        out = render_docx(content, _get_output_dir() / filename, title=title)
    except Exception as e:  # noqa: BLE001
        logger.error("docx_generation_failed", error=str(e), title=title[:100])
        return {
            "success": False,
            "output": f"❌ DOCX generation failed: {e}",
            "data": {"error": str(e)},
            "artifacts": [],
        }

    file_size = out.stat().st_size
    logger.info("docx_generated", filename=filename, size=file_size)
    download_url = f"/api/v1/artifacts/download/{filename}"
    return {
        "success": True,
        "output": f"Word doc created: {filename} ({file_size:,}b) | Download: {download_url}",
        "data": {"path": filename, "size": file_size, "download_url": download_url},
        "artifacts": [{"type": "document", "path": filename, "format": "docx"}],
    }


