async def handle_read_document(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Read an existing Word .docx: paragraphs (with indices) and tables."""
    rel_path = params.get("path", "")
    max_paragraphs = params.get("max_paragraphs", 500)
    if not isinstance(max_paragraphs, int) or max_paragraphs < 1:
        max_paragraphs = 500

    if not rel_path:
        return {"success": False, "output": "⚠️ 'path' is required.", "data": None, "artifacts": []}

    try:
        from docx import Document
    except ImportError:
        return {"success": False, "output": "python-docx not installed. Run: pip install python-docx", "data": None, "artifacts": []}

    path = _resolve_workspace_file(rel_path)
    if path is None:
        return {"success": False, "output": "Access denied: path resolves outside workspace.", "data": None, "artifacts": []}
    if not path.exists():
        return {"success": False, "output": f"File not found: {rel_path}", "data": None, "artifacts": []}

    try:
        doc = Document(str(path))
    except Exception as e:  # noqa: BLE001
        return {"success": False, "output": f"Cannot open document: {e}", "data": None, "artifacts": []}

    paragraphs = [p.text for p in doc.paragraphs]
    total_paras = len(paragraphs)
    shown = paragraphs[:max_paragraphs]
    truncated = total_paras > max_paragraphs

    tables_data: list[list[list[str]]] = []
    for tbl in doc.tables:
        tables_data.append([[c.text for c in row.cells] for row in tbl.rows])

    lines = [
        f"📄 {rel_path} | {total_paras} paragraph(s), {len(doc.tables)} table(s)"
        + (" (paragraphs truncated)" if truncated else ""),
        "",
    ]
    for idx, text in enumerate(shown):
        if text.strip():
            lines.append(f"   [{idx}] {text[:200]}")
    if tables_data:
        lines.append("")
        for ti, tbl in enumerate(tables_data):
            lines.append(f"   Table {ti}: {len(tbl)} row(s)")
            for r in tbl[:5]:
                lines.append(f"      {' | '.join(c[:30] for c in r)}")

    return {
        "success": True,
        "output": "\n".join(lines),
        "data": {
            "path": rel_path,
            "paragraphs": shown,
            "total_paragraphs": total_paras,
            "tables": tables_data,
            "truncated": truncated,
        },
        "artifacts": [],
    }


async def handle_edit_document(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Edit an existing .docx in place: replace text or edit specific paragraphs.

    Two edit shapes (provide 'edits' as a list):
    - {find, replace}: replace text across all paragraphs (preserves the run's
      style when the match sits within a single run).
    - {paragraph, text}: overwrite paragraph at index N with new text.
    Other paragraphs, tables, and document structure are preserved. Atomic save.
    """
    rel_path = params.get("path", "")
    edits = params.get("edits")

    if not rel_path:
        return {"success": False, "output": "⚠️ 'path' is required.", "data": None, "artifacts": []}
    if not isinstance(edits, list) or not edits:
        return {
            "success": False,
            "output": "⚠️ 'edits' must be a non-empty array of {find,replace} or {paragraph,text}.",
            "data": None,
            "artifacts": [],
        }

    try:
        from docx import Document
    except ImportError:
        return {"success": False, "output": "python-docx not installed. Run: pip install python-docx", "data": None, "artifacts": []}

    path = _resolve_workspace_file(rel_path)
    if path is None:
        return {"success": False, "output": "Access denied: path resolves outside workspace.", "data": None, "artifacts": []}
    if not path.exists():
        return {"success": False, "output": f"File not found: {rel_path}. Use generate_word_document to create it.", "data": None, "artifacts": []}

    try:
        doc = Document(str(path))
    except Exception as e:  # noqa: BLE001
        return {"success": False, "output": f"Cannot open document: {e}", "data": None, "artifacts": []}

    paras = doc.paragraphs
    applied: list[str] = []

    for idx, edit in enumerate(edits):
        if not isinstance(edit, dict):
            return {"success": False, "output": f"Edit #{idx + 1} must be an object.", "data": None, "artifacts": []}

        if "find" in edit and "replace" in edit:
            find, repl = str(edit["find"]), str(edit["replace"])
            if not find:
                return {"success": False, "output": f"Edit #{idx + 1}: 'find' cannot be empty.", "data": None, "artifacts": []}
            count = 0
            for p in paras:
                if find in p.text:
                    # Prefer run-level replace to keep formatting; fall back to
                    # rewriting the whole paragraph if the match spans runs.
                    replaced_in_run = False
                    for run in p.runs:
                        if find in run.text:
                            run.text = run.text.replace(find, repl)
                            replaced_in_run = True
                    if not replaced_in_run:
                        p.text = p.text.replace(find, repl)
                    count += 1
            applied.append(f"replace '{find[:30]}'→'{repl[:30]}' in {count} paragraph(s)")
        elif "paragraph" in edit and "text" in edit:
            pidx = edit["paragraph"]
            if not isinstance(pidx, int) or pidx < 0 or pidx >= len(paras):
                return {"success": False, "output": f"Edit #{idx + 1}: paragraph index {pidx} out of range (0..{len(paras) - 1}).", "data": None, "artifacts": []}
            paras[pidx].text = str(edit["text"])
            applied.append(f"set paragraph [{pidx}]")
        else:
            return {"success": False, "output": f"Edit #{idx + 1}: provide {{find,replace}} or {{paragraph,text}}.", "data": None, "artifacts": []}

    # Atomic save.
    import tempfile
    fd, tmp = tempfile.mkstemp(suffix=".docx", dir=str(path.parent))
    os.close(fd)
    try:
        doc.save(tmp)
        os.replace(tmp, str(path))
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise

    return {
        "success": True,
        "output": f"✏️ Edited {rel_path}: {len(applied)} operation(s) — {'; '.join(applied[:10])}",
        "data": {"path": rel_path, "edits_applied": len(applied)},
        "artifacts": [{"type": "file", "path": rel_path}],
    }


