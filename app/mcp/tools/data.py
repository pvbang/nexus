async def handle_generate_csv(params: dict[str, Any], **kwargs: Any) -> dict[str, Any]:
    """Generate a CSV file from structured data."""
    headers = params.get("headers", [])
    rows = params.get("rows", [])
    filename = params.get("filename", f"data_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv")

    if not rows:
        return {"success": False, "output": "Rows data is required", "data": None, "artifacts": []}

    try:
        output_buf = io.StringIO()
        writer = csv.writer(output_buf)

        if headers:
            writer.writerow(headers)

        for row in rows:
            if isinstance(row, dict):
                writer.writerow(row.values())
            elif isinstance(row, (list, tuple)):
                writer.writerow(row)
            else:
                writer.writerow([str(row)])

        csv_content = output_buf.getvalue()
        path = _get_output_dir() / filename
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(csv_content, encoding="utf-8")

        download_url = f"/api/v1/artifacts/download/{filename}"
        return {
            "success": True,
            "output": (
                f"📊 CSV file generated: {filename}\n"
                f"- Rows: {len(rows)}\n"
                f"- Columns: {len(headers) if headers else 'auto'}\n"
                f"- Download: {download_url}"
            ),
            "data": {"path": filename, "rows": len(rows), "download_url": download_url},
            "artifacts": [{"type": "file", "path": filename, "format": "csv"}],
        }
    except Exception as e:
        return {"success": False, "output": f"CSV generation failed: {e}", "data": None, "artifacts": []}


