def get_identity_section(agent_type: str) -> str:
    """
    Get agent identity string for system prompt.

    Uses static AGENT_IDENTITIES first (handcrafted, higher quality).
    Falls back to auto-generating from AGENT_TEMPLATES for 37+ specialist roles.

    Args:
        agent_type: Agent role key (core, researcher, developer, etc.)

    Returns:
        Identity string for the system prompt.
    """
    # Check static identities first (handcrafted, higher quality)
    if agent_type in AGENT_IDENTITIES:
        return AGENT_IDENTITIES[agent_type]

    # Auto-generate from AGENT_TEMPLATES (covers all Omni-Agent roles)
    try:
        from app.services.agent_spawner import AGENT_TEMPLATES
        template = AGENT_TEMPLATES.get(agent_type)
        if template:
            name = template.get("default_name", agent_type.replace("_", " ").title())
            avatar = template.get("avatar", "🤖")
            desc = template.get("description", "")
            personality = template.get("personality", "")
            background = template.get("background", "")
            expertise = template.get("expertise", [])

            identity = f"You are **{name}** {avatar} — a specialist agent in Nexus.\n\n"
            if desc:
                identity += f"{desc}\n\n"
            if background:
                identity += f"**Background**: {background}\n\n"
            if expertise:
                identity += f"**Expertise**: {', '.join(expertise)}\n\n"
            if personality:
                identity += f"**Your style**: {personality}\n\n"
            identity += (
                "## Core Operating Principles\n"
                "- You work in a SHARED workspace with other agents. "
                "Read and edit teammates' files when your task requires it.\n"
                "- Fix root causes, not symptoms. No hardcoding or superficial patches.\n"
                "- Clean code: if 200 lines could be 50, rewrite.\n"
                "- Surgical changes: only touch what your assignment requires.\n"
                "- Verify your output works before declaring done.\n"
                "- Output language matches the user's language.\n"
            )
            return identity
    except ImportError:
        pass

    # Final fallback: generic identity
    role_display = agent_type.replace("_", " ").title()
    return (
        f"You are a **{role_display} Agent** in Nexus.\n\n"
        f"Apply your specialized expertise to help complete tasks effectively."
    )
