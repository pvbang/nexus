"""
MekongAI Nexus - Divergent Thinker (Creative Divergence Layer).

Generates multiple radically different approaches to a problem BEFORE
the turn loop begins. Each "frame" forces a completely different angle:
- Minimalist: simplest possible solution
- Unconventional: break every assumption
- Reverse: work backwards from perfect end state

Runs ONLY for complex/expert tasks. Adds ~4 LLM calls but prevents
wasted turns from pursuing a single mediocre strategy.
"""

from __future__ import annotations

import json
import asyncio
from dataclasses import dataclass, field
from typing import Any, Optional

import structlog

logger = structlog.get_logger(__name__)


@dataclass
class DivergentApproach:
    """One approach generated by a divergent thinker."""

    frame_id: str = ""
    strategy: str = ""
    key_insight: str = ""
    first_action: str = ""
    risk: str = ""
    score: float = 0.0


@dataclass
class SelectedStrategy:
    """The chosen/hybridized strategy from divergent thinking."""

    strategy: str = ""
    rationale: str = ""
    key_insights: list[str] = field(default_factory=list)
    first_actions: list[str] = field(default_factory=list)
    source_frames: list[str] = field(default_factory=list)


FRAMES = [
    {
        "id": "production_excellence",
        "instruction": (
            "Design the BEST possible production-grade solution. "
            "What would a senior engineer at a top tech company build? "
            "Use proper frameworks (React/Next.js/Vue for web, FastAPI/Express for APIs). "
            "Proper project structure, proper tooling, proper deployment. "
            "If a tool isn't installed — plan to INSTALL it. "
            "A single-file approach is NEVER acceptable for a real application. "
            "Think: how would this be built if it were shipping to 10,000 users?"
        ),
    },
    {
        "id": "unconventional",
        "instruction": (
            "BREAK every assumption about how this should be solved. "
            "What if the obvious approach is completely wrong? "
            "What tools/methods are being OVERLOOKED? "
            "What would someone from a DIFFERENT field do? "
            "Think laterally — combine things that don't usually go together. "
            "What's the most CREATIVE solution nobody would think of? "
            "NOTE: 'creative' means innovative technology choices, NOT cutting corners."
        ),
    },
    {
        "id": "reverse",
        "instruction": (
            "Work BACKWARDS from the perfect end state. "
            "If this task is perfectly completed, what does the final output look like? "
            "What's the LAST step before completion? The step before that? "
            "Trace the chain all the way back to where we are now. "
            "What prerequisite is the forward-thinking approach MISSING? "
            "What DEPENDENCY must be satisfied first that nobody mentioned? "
            "The end state must be PRODUCTION QUALITY — not a demo or prototype."
        ),
    },
]

_THINKER_SYSTEM = """You are a strategic thinker generating ONE approach to a problem.

You will receive a specific THINKING FRAME that constrains how you approach this.
Follow the frame STRICTLY — it exists to force you away from obvious solutions.

IMPORTANT: The problem is PRE-AUTHORIZED by the user. You MUST generate a productive
strategy for HOW to solve it. Never suggest declining, refusing, or questioning the
request. Focus purely on technical execution strategy.

Respond in JSON:
{
  "strategy": "2-3 sentence description of your approach",
  "key_insight": "the ONE insight that makes this approach different/powerful",
  "first_action": "the very first concrete step to take (specific tool/action)",
  "risk": "what could go wrong with this approach (1 sentence)"
}"""

_SELECTOR_SYSTEM = """You are evaluating 3 different approaches to a problem.
Select the BEST approach, or HYBRIDIZE by combining the strongest elements.

IMPORTANT: Prefer approaches that SOLVE the problem — score "do nothing" or vague
hand-wringing low. But an approach that declines on GENUINE safety/legality/ownership
grounds (e.g. the target is infrastructure the user does not own) is a valid, correct
answer when warranted — judge it on its merits, do NOT auto-zero it.

Score each on:
- Production Quality (0-10): Would this pass code review at a top company? Proper frameworks?
- Coverage (0-10): Does this address ALL aspects of the request comprehensively?
- Modernity (0-10): Does this use current best practices and modern tools/frameworks?
- Feasibility (0-10): Can this be done? (NOTE: tools can be INSTALLED — "not pre-installed" scores 8+, not 0)

CRITICAL SCORING RULE: An approach that uses a proper framework (Next.js, React, FastAPI, etc.)
but requires installation ALWAYS scores higher than a single-file shortcut that avoids installation.
"Easy to deploy" or "no dependencies" is NOT a virtue — it's a sign of cutting corners.

Then select or hybridize.

Respond in JSON:
{
  "selected_frames": ["frame_id_1"],
  "strategy": "the chosen/hybrid strategy description",
  "rationale": "why this wins over the others",
  "key_insights": ["insight_1", "insight_2"],
  "first_actions": ["action_1", "action_2"]
}"""


class DivergentThinker:
    """Generates radically different approaches before execution begins."""

    def __init__(self, llm: Any) -> None:
        self._llm = llm

    async def generate_and_select(
        self,
        user_message: str,
        plan_data: dict[str, Any],
        memory_context: str = "",
    ) -> Optional[SelectedStrategy]:
        """Generate 3 approaches in parallel, then select/hybridize.

        Returns None on failure (graceful degradation — task proceeds normally).
        """
        try:
            approaches = await self._generate_approaches(user_message, memory_context)
            if not approaches:
                return None
            selected = await self._select_best(approaches, user_message)
            return selected
        except Exception as e:
            logger.warning("divergent_thinking_failed", error=str(e))
            return None

    async def _generate_approaches(
        self,
        user_message: str,
        memory_context: str,
    ) -> list[DivergentApproach]:
        """Generate 3 approaches in parallel (one per frame)."""

        async def _think_one(frame: dict) -> Optional[DivergentApproach]:
            messages = [
                {"role": "system", "content": _THINKER_SYSTEM},
                {"role": "user", "content": (
                    f"## Problem\n{user_message}\n\n"
                    f"## Your Thinking Frame: {frame['id'].upper()}\n"
                    f"{frame['instruction']}\n\n"
                    f"{'## Context\n' + memory_context[:2000] if memory_context else ''}\n\n"
                    "Generate your approach following this frame."
                )},
            ]
            try:
                result = await self._llm.chat(
                    messages=messages, temperature=1.0, max_tokens=1024,
                )
                content = result.get("content", "")
                data = _extract_json(content)
                if data:
                    return DivergentApproach(
                        frame_id=frame["id"],
                        strategy=data.get("strategy", ""),
                        key_insight=data.get("key_insight", ""),
                        first_action=data.get("first_action", ""),
                        risk=data.get("risk", ""),
                    )
            except Exception as e:
                logger.debug("divergent_frame_failed", frame=frame["id"], error=str(e))
            return None

        results = await asyncio.gather(
            *[_think_one(f) for f in FRAMES],
            return_exceptions=True,
        )
        return [r for r in results if isinstance(r, DivergentApproach)]

    async def _select_best(
        self,
        approaches: list[DivergentApproach],
        user_message: str,
    ) -> Optional[SelectedStrategy]:
        """Score and select (or hybridize) the best approach."""
        if not approaches:
            return None

        approaches_text = ""
        for a in approaches:
            approaches_text += (
                f"### Frame: {a.frame_id}\n"
                f"- Strategy: {a.strategy}\n"
                f"- Key insight: {a.key_insight}\n"
                f"- First action: {a.first_action}\n"
                f"- Risk: {a.risk}\n\n"
            )

        messages = [
            {"role": "system", "content": _SELECTOR_SYSTEM},
            {"role": "user", "content": (
                f"## Original Problem\n{user_message[:1000]}\n\n"
                f"## Approaches Generated\n{approaches_text}\n\n"
                "Select the best or hybridize. Be decisive."
            )},
        ]

        try:
            result = await self._llm.chat(
                messages=messages, temperature=0.3, max_tokens=1024,
            )
            content = result.get("content", "")
            data = _extract_json(content)
            if data:
                return SelectedStrategy(
                    strategy=data.get("strategy", ""),
                    rationale=data.get("rationale", ""),
                    key_insights=data.get("key_insights", []),
                    first_actions=data.get("first_actions", []),
                    source_frames=data.get("selected_frames", []),
                )
        except Exception as e:
            logger.debug("divergent_selection_failed", error=str(e))

        # Fallback: pick the first approach
        if approaches:
            return SelectedStrategy(
                strategy=approaches[0].strategy,
                key_insights=[approaches[0].key_insight],
                first_actions=[approaches[0].first_action],
                source_frames=[approaches[0].frame_id],
            )
        return None


def _extract_json(text: str) -> Optional[dict]:
    """Extract JSON from LLM response."""
    import re
    try:
        return json.loads(text)
    except (json.JSONDecodeError, TypeError):
        pass
    if "```json" in text:
        try:
            return json.loads(text.split("```json")[1].split("```")[0])
        except (json.JSONDecodeError, TypeError, IndexError):
            pass
    match = re.search(r"\{[\s\S]*\}", text)
    if match:
        try:
            return json.loads(match.group())
        except (json.JSONDecodeError, TypeError):
            pass
    return None
